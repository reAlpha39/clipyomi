//! IPADIC's conjugation table (活用型/活用形) and the JMdict POS mapping onto it.
//!
//! `CLASSES` is generated by `tools/gen_conjugation_table.py` from
//! mecab-ipadic's CSV lexicon into `table_data.rs`; see that generator's
//! docstring for exact provenance and `crates/jparser/assets/IPADIC_NOTICE`
//! for the licence notice its retention requires. Nothing here is derived
//! from Translation Aggregator.

pub use crate::engine::table_data::CLASSES;
pub use crate::engine::{ClassId, FormId};

/// One IPADIC conjugation class (活用型).
pub struct Class {
    pub name: &'static str,
    /// What the base form adds to the stem: `る` for 一段, `する` for サ変・スル.
    pub remove: &'static str,
    pub is_adjective: bool,
    pub forms: &'static [Form],
}

/// One conjugation form (活用形) of a class, and the suffix it puts on the stem.
pub struct Form {
    pub name: &'static str,
    pub suffix: &'static str,
}

/// JMdict POS code to IPADIC conjugation class.
///
/// Hand-written: JMdict's POS vocabulary and IPADIC's 活用型 vocabulary have
/// no defined relationship (master plan §4.3), so this is the mapping that
/// connects them. Every row is checked by the tests below — the code must
/// map to a class the generated table actually carries.
///
/// This list is not exhaustive by design. A JMdict verb/adjective POS code
/// is only given a row here when a class in `CLASSES` can be justified for
/// it without guessing at Japanese grammar the way `tools/gen_conjugation_table.py`
/// couldn't (see task-4-report.md for the full reasoning and the codes
/// deliberately left out — `POS_WITHOUT_A_CLASS` below names them).
pub const JMDICT_POS_CLASS: &[(&str, &str)] = &[
    ("v1", "一段"),
    ("v5k", "五段・カ行イ音便"),
    ("v5k-s", "五段・カ行促音便"),
    ("v5g", "五段・ガ行"),
    ("v5s", "五段・サ行"),
    ("v5t", "五段・タ行"),
    ("v5n", "五段・ナ行"),
    ("v5b", "五段・バ行"),
    ("v5m", "五段・マ行"),
    ("v5r", "五段・ラ行"),
    ("v5u", "五段・ワ行促音便"),
    ("vk", "カ変・クル"),
    ("vs-i", "サ変・スル"),
    ("adj-i", "形容詞・アウオ段"),
    // Below: completed from the generator's printed class list against the
    // JMdict POS codes in tests/fixtures/{jmdict_subset,gold_jmdict_subset}.xml.
    // "五段・ラ行アル" carries exactly one lemma, ある — the class name
    // itself names the special case v5aru's description does.
    ("v5aru", "五段・ラ行アル"),
    // "五段・ラ行特殊" carries いらっしゃる, おっしゃる, くださる, ござる,
    // なさる — the textbook v5r-i "irregular ru verb" set.
    ("v5r-i", "五段・ラ行特殊"),
    // v5u already took 五段・ワ行促音便 (the sokuon pattern most -u verbs
    // use); 五段・ワ行ウ音便's lemmas (問う, 乞う, 厭う, 添う...) are
    // exactly v5u-s's "special class" u-onbin verbs.
    ("v5u-s", "五段・ワ行ウ音便"),
    // vr's own definition — "irregular ru verb, plain form ends with -ri"
    // — is the textbook definition of ラ変 (ra-gyou henkaku katsuyou); the
    // class's one lemma is あり.
    ("vr", "ラ変"),
    // Confirmed against the fixtures directly: entries for 愛する and
    // 圧する are tagged vs-s, and both lemmas (あいする, あっする) are in
    // サ変・−スル's list. vs-i (above) already took the bare する itself.
    ("vs-s", "サ変・−スル"),
    // adj-ix is literally "adjective (keiyoushi) - yoi/ii class"; the
    // generated table has one class for exactly that lemma, いい.
    ("adj-ix", "形容詞・イイ"),
];

/// Every JMdict POS code found in the two fixture corpora
/// (`jmdict_subset.xml`, `gold_jmdict_subset.xml`) that has no row in
/// [`JMDICT_POS_CLASS`], and why. A missing row is a visible gap tracked
/// here, not a silently wrong one, and covers two different reasons:
/// grammatical categories that were never going to conjugate at all, and
/// codes that name a real verb/adjective category IPADIC just can't be
/// pinned to one class for.
///
/// Never conjugate at all — plain grammatical categories (nouns, particles,
/// adverbs, and the like):
/// `n`, `n-pref`, `n-suf`, `adv`, `adv-to`, `conj`, `ctr`, `exp`, `int`,
/// `num`, `pn`, `pref`, `prt`, `suf`, `unc`.
///
/// Verb/adjective-shaped, but too coarse to name one class:
/// - `v-unspec`, `vs`, `vi`, `vt`: `v-unspec` is JMdict's own "no specific
///   class" tag; `vs` tags a *noun* that takes する (confirmed against the
///   fixture: it co-occurs with `n`, never carries its own conjugation);
///   `vi`/`vt` are transitivity markers that always accompany a real
///   verb-class code.
/// - `aux`, `aux-v`, `aux-adj`, `cop`: JMdict's generic auxiliary/copula
///   tags. Unlike `v5k` or `vk`, these don't name a specific conjugation
///   paradigm — ます, ない, た, だ and です are all tagged `aux-v` (or
///   `cop` for the copulas), but conjugate via entirely different IPADIC
///   classes (特殊・マス, 特殊・ナイ, 特殊・タ, 特殊・ダ, 特殊・デス
///   respectively). The POS code alone can't tell which one applies; only
///   the specific lemma can, and this table maps codes, not lemmas.
/// - `vs-c`: "su verb — precursor to the modern suru" covers a mix. Some
///   entries carry a real godan code alongside it (熟す: `v5s vs-c vi`) and
///   are already covered there. Others don't: 為す/す (ent_seq 2219050,
///   `<s_inf>literary form of する</s_inf>`) and 屈す (ent_seq 2409930,
///   `arch`) are tagged only `vs-c` (plus `vi`/`vt`), with no accompanying
///   conjugation-class code — archaic literary す-forms IPADIC has no class
///   for, the same "no defensible class" situation as `vn`/`v2*`/`v4*` below.
/// - `vn`, all `v2*`, all `v4*`: archaic (文語) nidan/yodan/irregular
///   conjugation codes. IPADIC's 上二/下二/四段 classes are too sparse and
///   too loosely named to justify a 1:1 mapping without guessing at
///   classical grammar rather than reading the enumerable class list (the
///   very thing this table is built to avoid) — e.g. there is no 上二/下二
///   class at all for the ア/ワ/ラ rows several v2 codes need, and `vn`
///   ("irregular nu verb", archaic 往ぬ) would otherwise collide with
///   `特殊・ヌ`, which is a different word (the ぬ negation auxiliary).
/// - `adj-f`, `adj-na`, `adj-nari`, `adj-no`, `adj-pn`, `adj-t`: IPADIC has
///   no 形容動詞 (na-adjective) class at all — checked directly: every
///   class name under 文語・* that looks adjectival (`文語・ナリ` included)
///   is filed under 品詞=助動詞 (auxiliary verb, e.g. classical なり/たり),
///   not 形容詞/形容動詞. These adjective stems are invariant in IPADIC;
///   only the copula/auxiliary attached to them conjugates, and that
///   auxiliary is a separate dictionary entry with its own POS tag.
/// - `adj-ku`, `adj-shiku`: archaic ku/shiku-katsuyou adjectives. No class
///   in the generated table represents them (the `文語・*` classes are all
///   auxiliaries, not adjectives — see above).
