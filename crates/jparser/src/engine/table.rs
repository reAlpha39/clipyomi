pub fn class_for_pos(pos: &str) -> Option<ClassId> {
    let name = JMDICT_POS_CLASS.iter().find(|(p, _)| *p == pos)?.1;
    CLASSES
        .iter()
        .position(|c| c.name == name)
        .map(|i| i as ClassId)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn class(name: &str) -> &'static Class {
        CLASSES
            .iter()
            .find(|c| c.name == name)
            .unwrap_or_else(|| panic!("no class {name}; the generator's class list changed"))
    }

    fn suffix(class_name: &str, form_name: &str) -> &'static str {
        class(class_name)
            .forms
            .iter()
            .find(|f| f.name == form_name)
            .unwrap_or_else(|| panic!("{class_name} has no form {form_name}"))
            .suffix
    }

    #[test]
    fn ichidan_removes_ru_and_has_an_empty_stem_form() {
        assert_eq!(class("一段").remove, "る");
        assert_eq!(suffix("一段", "基本形"), "る");
        assert_eq!(suffix("一段", "連用形"), "", "食べ is the bare stem");
    }

    #[test]
    fn godan_ka_i_onbin_keeps_its_irregular_ta_form() {
        // 書く: 連用形 is 書き but 連用タ接続 is 書い. That split is why IPADIC
        // has a separate class for it, and it is the check that the pivot
        // reads 活用形 rather than guessing.
        assert_eq!(class("五段・カ行イ音便").remove, "く");
        assert_eq!(suffix("五段・カ行イ音便", "連用形"), "き");
        assert_eq!(suffix("五段・カ行イ音便", "連用タ接続"), "い");
    }

    #[test]
    fn suru_has_an_empty_stem_so_every_suffix_is_the_whole_surface() {
        assert_eq!(class("サ変・スル").remove, "する");
        assert_eq!(suffix("サ変・スル", "未然形"), "し");
    }

    #[test]
    fn the_adjective_class_is_marked() {
        assert!(class("形容詞・アウオ段").is_adjective);
        assert!(!class("一段").is_adjective);
    }

    #[test]
    fn the_auxiliaries_the_label_chain_needs_are_present() {
        // Master plan §7.3's example chain: させ|られ|ませ|ん|でし|た.
        for name in [
            "特殊・タ",
            "特殊・マス",
            "特殊・ヌ",
            "特殊・デス",
            "特殊・ナイ",
        ] {
            assert!(!class(name).forms.is_empty(), "{name} has no forms");
        }
    }

    #[test]
    fn every_jmdict_verb_pos_in_the_fixture_maps_to_a_real_class() {
        for pos in JMDICT_POS_CLASS.iter().map(|(p, _)| *p) {
            assert!(class_for_pos(pos).is_some(), "{pos} maps to nothing");
        }
        for (pos, name) in JMDICT_POS_CLASS {
            assert!(
                CLASSES.iter().any(|c| c.name == *name),
                "{pos} maps to {name}, which the generated table does not have"
            );
        }
    }

    /// Every distinct JMdict POS code `path` actually uses, parsed at test
    /// time with `crate::jmdict`'s streaming reader (already relied on to
    /// decode `<pos>&code;</pos>` entity references correctly — see that
    /// module's `decode_text`) rather than a hand-maintained snapshot. A
    /// snapshot can silently go stale when a fixture is regenerated; this
    /// can't.
    fn pos_codes_in(path: &str) -> std::collections::BTreeSet<String> {
        let file = std::fs::File::open(path).unwrap_or_else(|e| panic!("open {path}: {e}"));
        let mut codes = std::collections::BTreeSet::new();
        for entry in crate::jmdict::parse_entries(std::io::BufReader::new(file)) {
            let entry = entry.unwrap_or_else(|e| panic!("parse {path}: {e}"));
            for sense in entry.senses {
                codes.extend(sense.pos);
            }
        }
        codes
    }

    #[test]
    fn every_pos_in_the_fixtures_is_mapped_or_a_documented_gap() {
        // Strengthens the test above, which only iterates JMDICT_POS_CLASS
        // itself and so only proves internal consistency. This one checks
        // against what the fixtures actually use, extracted from the XML
        // itself rather than a hardcoded list: every POS code must either
        // have a row, or be named in POS_WITHOUT_A_CLASS — never silently
        // absent from both.
        let mut codes = pos_codes_in(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/tests/fixtures/jmdict_subset.xml"
        ));
        codes.extend(pos_codes_in(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/tests/fixtures/gold_jmdict_subset.xml"
        )));

        let mut unaccounted = Vec::new();
        for pos in &codes {
            let mapped = JMDICT_POS_CLASS.iter().any(|(p, _)| p == pos);
            let documented_gap = POS_WITHOUT_A_CLASS.contains(&pos.as_str());
            assert!(
                !(mapped && documented_gap),
                "{pos} is both mapped and listed in POS_WITHOUT_A_CLASS"
            );
            if !mapped && !documented_gap {
                unaccounted.push(pos.clone());
            }
        }
        assert!(
            unaccounted.is_empty(),
            "POS codes in the fixtures with no row and no documented gap: {unaccounted:?}"
        );
    }
}
